class ScheduleRecordScreen extends ConsumerStatefulWidget {
  const ScheduleRecordScreen({
    this.editingScheduleId,
    this.initialDate,
    super.key,
  });

  final int? editingScheduleId;

  /// 新規作成時の日付プリセット (カレンダー日付タップ時)
  final DateTime? initialDate;

  static Future<bool?> push(
    BuildContext context, {
    int? editingScheduleId,
    DateTime? initialDate,
  }) {
    return Navigator.of(context).push<bool>(
      MaterialPageRoute<bool>(
        builder: (_) => ScheduleRecordScreen(
          editingScheduleId: editingScheduleId,
          initialDate: initialDate,
        ),
      ),
    );
  }

  @override
  ConsumerState<ScheduleRecordScreen> createState() =>
      _ScheduleRecordScreenState();
}

class _ScheduleRecordScreenState
    extends ConsumerState<ScheduleRecordScreen> {
  final TextEditingController _titleC = TextEditingController();
  final TextEditingController _notesC = TextEditingController();

  bool _loaded = false;
  bool _isSubmitting = false;
  ScheduleEntity? _editing;

  ScheduleCategory _category = ScheduleCategory.custom;
  DateTime _date = DateTime.now();
  TimeOfDay? _time;
  ScheduleRecurrence _recurrence = ScheduleRecurrence.none;
  ScheduleNotificationTiming _notification =
      ScheduleNotificationTiming.none;
  Set<int> _selectedPetIds = <int>{};

  // build 47b (Scope B4): category=medication 時のみ表示する繰り返し通知
  // フィールド。HH:mm 文字列のリスト + 曜日 bitset (Set<int>)。
  // weekdays が空 = 毎日扱い (旧 medication_reminders と同じセマンティクス)。
  List<String> _times = <String>[];
  Set<int> _weekdays = <int>{};

  String? _titleError;

  @override
  void initState() {
    super.initState();
    if (widget.initialDate != null) {
      _date = widget.initialDate!;
    }
    if (widget.editingScheduleId != null) {
      Future<void>.microtask(_loadExisting);
    } else {
      _loaded = true;
    }
  }

  @override
  void dispose() {
    _titleC.dispose();
    _notesC.dispose();
    super.dispose();
  }

  Future<void> _loadExisting() async {
    try {
      final ScheduleEntity? s = await ref
          .read(schedulesRepositoryProvider)
          .getById(widget.editingScheduleId!);
      if (s == null) {
        if (mounted) Navigator.of(context).pop();
        return;
      }
      final DateTime dt = DateTime.fromMillisecondsSinceEpoch(s.scheduledAt);
      if (!mounted) return;
      setState(() {
        _editing = s;
        _titleC.text = s.title;
        _notesC.text = s.notes ?? '';
        _category = s.category;
        _date = dt;
        _time = s.hasTime ? TimeOfDay(hour: dt.hour, minute: dt.minute) : null;
        _recurrence = s.recurrence;
        _notification = s.notificationTiming;
        _selectedPetIds = s.relatedPetIds
            .map((String id) => int.tryParse(id))
            .whereType<int>()
            .toSet();
        // build 47b: medication 用 times/weekdays を復元
        _times = _decodeTimesJson(s.times);
        _weekdays = _decodeWeekdaysBits(s.weekdaysBits);
        _loaded = true;
      });
    } catch (e, st) {
      PetloLogger.instance.w('load schedule failed', error: e, stackTrace: st);
    }
  }

  bool get _isEditing => widget.editingScheduleId != null;
  bool get _isAutoGenerated => _editing?.isAutoGenerated ?? false;

  Future<void> _save() async {
    if (_isSubmitting) return;
    final String title = _titleC.text.trim();
    if (title.isEmpty) {
      setState(() => _titleError = AppLocalizations.of(context).common_input_invalid);
      return;
    }

    setState(() {
      _isSubmitting = true;
      _titleError = null;
    });

    try {
      final DateTime scheduled = _time == null
          ? DateTime(_date.year, _date.month, _date.day)
          : DateTime(_date.year, _date.month, _date.day, _time!.hour,
              _time!.minute);
      final int scheduledMs = scheduled.millisecondsSinceEpoch;

      final bool isMedication = _category == ScheduleCategory.medication;
      final SchedulesRepository repo = ref.read(schedulesRepositoryProvider);
      int? savedScheduleId;
      if (_isEditing) {
        await repo.update(
          scheduleId: widget.editingScheduleId!,
          title: title,
          category: _category,
          scheduledAtMsec: scheduledMs,
          hasTime: _time != null,
          recurrence: _recurrence,
          notificationTiming: _notification,
          notes: _notesC.text.trim(),
          relatedPetIds: _selectedPetIds.toList(),
          times: isMedication ? _times : null,
          weekdays: isMedication ? _weekdays : null,
          clearMedicationFields: !isMedication,
        );
        savedScheduleId = widget.editingScheduleId;
      } else {
        final String groupId = ref.read(currentGroupIdProvider);
        savedScheduleId = await repo.create(
          groupId: groupId,
          title: title,
          category: _category,
          scheduledAtMsec: scheduledMs,
          hasTime: _time != null,
          recurrence: _recurrence,
          notificationTiming: _notification,
          notes: _notesC.text.trim(),
          relatedPetIds: _selectedPetIds.toList(),
          times: isMedication ? _times : null,
          weekdays: isMedication ? _weekdays : null,
        );
      }

      // build 73: 保存後は 3 系統まとめて再割り当てする。
      // 個別 sync では総量 64 を守れないため (他系統の使用量が見えない)。
      if (savedScheduleId != null) {
        // build 73: 通知を期待した文脈で権限を要求する。
        // 未確定ならここで OS ダイアログ、拒否済みなら設定への導線。
        if (mounted) {
          await NotificationPermissionPrompt.ensureGranted(context);
        }
        await ref
            .read(notificationCoordinatorProvider)
            .rescheduleAll(isPro: ref.read(isProProvider));
      }

      if (!mounted) return;
      Navigator.of(context).pop(true);
    } catch (e, st) {
      PetloLogger.instance.w('save schedule failed', error: e, stackTrace: st);
      if (!mounted) return;
      setState(() => _isSubmitting = false);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content:
              Text(AppLocalizations.of(context).common_save_failed),
          behavior: SnackBarBehavior.floating,
        ),
      );
    }
  }

  Future<void> _delete() async {
    if (widget.editingScheduleId == null) return;
    final bool ok = await RecordDeleteHelper.confirm(context);
    if (!ok || !mounted) return;
    final bool deleted = await ref
        .read(schedulesRepositoryProvider)
        .softDelete(widget.editingScheduleId!);
    // build 73: 削除後も全体を再割り当てする。
    // 消えた分の枠が他系統に回るので、個別 cancel では不十分。
    if (deleted) {
      await ref
          .read(notificationCoordinatorProvider)
          .rescheduleAll(isPro: ref.read(isProProvider));
    }
    if (!mounted) return;
    if (deleted) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(AppLocalizations.of(context).common_deleted),
          behavior: SnackBarBehavior.floating,
        ),
      );
      Navigator.of(context).pop(true);
    }
  }

  @override
  Widget build(BuildContext context) {
    final AppColors colors = AppColors.of(context);
    final AppTypography typo = AppTypography.of(context);
    final AppLocalizations l10n = AppLocalizations.of(context);

    if (!_loaded) {
      return Scaffold(
        backgroundColor: colors.bg,
        appBar: AppBar(backgroundColor: colors.bg, elevation: 0),
        body: const Center(child: CircularProgressIndicator()),
      );
    }

    return Scaffold(
      backgroundColor: colors.bg,
      appBar: AppBar(
        backgroundColor: colors.bg,
        foregroundColor: colors.fg,
        elevation: 0,
        scrolledUnderElevation: 0,
        title: Text(
          (_isEditing
                  ? l10n.schedule_appbar_edit
                  : l10n.schedule_appbar_new)
              .toUpperCase(),
          style: typo.metaSmall.copyWith(letterSpacing: 10 * 0.2),
        ),
        centerTitle: true,
        leading: TextButton(
          onPressed: () => Navigator.of(context).pop(false),
          child: Text(
            l10n.common_cancel.toUpperCase(),
            style: typo.metaSmall.copyWith(color: colors.fgMuted),
          ),
        ),
        leadingWidth: 80,
        actions: <Widget>[
          if (_isEditing)
            IconButton(
              icon: Icon(Icons.delete_outline,
                  color: colors.fgMuted, size: 22),
              onPressed: _delete,
              tooltip: l10n.common_delete,
            ),
        ],
      ),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.fromLTRB(
            AppDimensions.paddingPage,
            AppDimensions.paddingPage,
            AppDimensions.paddingPage,
            AppDimensions.paddingPage * 2,
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: <Widget>[
              SectionLabel(
                l10n.schedule_list_eyebrow,
                size: EyebrowSize.large,
                padding: const EdgeInsets.fromLTRB(
                    0, 0, 0, AppDimensions.paddingSection),
              ),

              // 自動生成バナー
              if (_isAutoGenerated)
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.all(12),
                  margin: const EdgeInsets.only(
                      bottom: AppDimensions.gapXLarge),
                  decoration: BoxDecoration(
                    color: colors.bgSoft,
                    border: Border.all(color: colors.line),
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: <Widget>[
                      Text(
                        l10n.schedule_auto_generated_label,
                        style: typo.bodyMedium
                            .copyWith(fontWeight: FontWeight.w600),
                      ),
                      const SizedBox(height: 4),
                      Text(
                        l10n.schedule_auto_generated_helper,
                        style: typo.bodySmall
                            .copyWith(color: colors.fgMuted, height: 1.4),
                      ),
                    ],
                  ),
                ),

              // タイトル
              EditorialTextField(
                label: l10n.schedule_field_title,
                controller: _titleC,
                hint: l10n.schedule_field_title_hint,
                required: true,
                maxLength: 100,
                errorText: _titleError,
                onChanged: (_) {
                  if (_titleError != null) {
                    setState(() => _titleError = null);
                  }
                },
              ),
              const SizedBox(height: AppDimensions.gapXLarge),

              // 種類
              SectionLabel(l10n.schedule_field_category),
              const SizedBox(height: 8),
              _CategorySelector(
                value: _category,
                onChanged: (ScheduleCategory c) =>
                    setState(() => _category = c),
              ),
              const SizedBox(height: AppDimensions.paddingSection),

              // build 47b (Scope B4): category=medication 時のみ
              // times[] + weekdaysBits の入力 UI を出す。
              if (_category == ScheduleCategory.medication) ...<Widget>[
                _MedicationScheduleFields(
                  times: _times,
                  weekdays: _weekdays,
                  onTimesChanged: (List<String> t) =>
                      setState(() => _times = t),
                  onWeekdaysChanged: (Set<int> w) =>
                      setState(() => _weekdays = w),
                ),
                const SizedBox(height: AppDimensions.paddingSection),
              ],

              // 日付
              DateField(
                label: l10n.schedule_field_date,
                value: _date,
                required: true,
                firstDate: DateTime(DateTime.now().year - 5),
                lastDate: DateTime.now().add(const Duration(days: 365 * 10)),
                onChanged: (DateTime? d) {
                  if (d != null) setState(() => _date = d);
                },
              ),
              const SizedBox(height: AppDimensions.gapXLarge),

              // 時刻
              _TimeRow(
                value: _time,
                onChanged: (TimeOfDay? t) => setState(() => _time = t),
              ),
              const SizedBox(height: AppDimensions.paddingSection),

              // 繰り返し
              SectionLabel(l10n.schedule_field_recurrence),
              const SizedBox(height: 8),
              _RecurrenceSelector(
                value: _recurrence,
                onChanged: (ScheduleRecurrence r) =>
                    setState(() => _recurrence = r),
              ),
              const SizedBox(height: AppDimensions.paddingSection),

              // 通知
              SectionLabel(l10n.schedule_field_notification),
              const SizedBox(height: 8),
              _NotificationSelector(
                value: _notification,
                onChanged: (ScheduleNotificationTiming n) =>
                    setState(() => _notification = n),
              ),
              const SizedBox(height: AppDimensions.paddingSection),

              // メモ
              EditorialTextField(
                label: l10n.schedule_field_notes,
                controller: _notesC,
                hint: l10n.schedule_field_notes_hint,
                maxLines: 3,
                minLines: 2,
              ),
              const SizedBox(height: AppDimensions.paddingSection),

              // 関連ペット
              SectionLabel(l10n.schedule_field_pets),
              const SizedBox(height: 8),
              _RelatedPetsSelector(
                selected: _selectedPetIds,
                onChanged: (Set<int> ids) =>
                    setState(() => _selectedPetIds = ids),
              ),
              const SizedBox(height: AppDimensions.paddingSection * 1.5),

              PrimaryButton(
                label: _isSubmitting
                    ? l10n.common_saving
                    : (_isEditing ? l10n.common_update : l10n.common_save),
                onPressed: _isSubmitting ? null : _save,
              ),
            ],
          ),
        ),
      ),
    );
  }
}

