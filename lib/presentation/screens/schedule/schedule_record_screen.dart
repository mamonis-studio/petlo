class _Chip extends StatelessWidget {
  const _Chip({
    required this.label,
    required this.selected,
    required this.onTap,
  });

  final String label;
  final bool selected;
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    final AppColors colors = AppColors.of(context);
    return InkWell(
      onTap: onTap,
      child: AnimatedContainer(
        duration: const Duration(milliseconds: 120),
        padding:
            const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
        decoration: BoxDecoration(
          color: selected ? colors.fg : colors.bg,
          border: Border.all(color: colors.fg, width: 1),
        ),
        child: Text(
          label,
          style: TextStyle(
            fontFamily: 'Manrope',
            fontSize: 12,
            fontWeight:
                selected ? FontWeight.w700 : FontWeight.w500,
            color: selected ? colors.bg : colors.fg,
          ),
        ),
      ),
    );
  }
}

class _TimeRow extends StatelessWidget {
  const _TimeRow({required this.value, required this.onChanged});

  final TimeOfDay? value;
  final ValueChanged<TimeOfDay?> onChanged;

  @override
  Widget build(BuildContext context) {
    final AppColors colors = AppColors.of(context);
    final AppTypography typo = AppTypography.of(context);
    final AppLocalizations l10n = AppLocalizations.of(context);
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: <Widget>[
        EyebrowText(l10n.schedule_field_time_optional),
        const SizedBox(height: AppDimensions.gapSmall),
        Row(
          children: <Widget>[
            Expanded(
              child: InkWell(
                onTap: () async {
                  final TimeOfDay? picked = await showTimePicker(
                    context: context,
                    initialTime: value ?? TimeOfDay.now(),
                  );
                  if (picked != null) onChanged(picked);
                },
                child: Container(
                  padding: const EdgeInsets.symmetric(vertical: 8),
                  decoration: BoxDecoration(
                    border: Border(
                      bottom: BorderSide(color: colors.line),
                    ),
                  ),
                  child: Text(
                    value == null
                        ? l10n.schedule_field_time_off
                        : value!.format(context),
                    style: typo.bodyLarge.copyWith(
                      color: value == null
                          ? colors.fgFaint
                          : colors.fg,
                    ),
                  ),
                ),
              ),
            ),
            if (value != null)
              IconButton(
                icon: Icon(Icons.close, size: 18, color: colors.fgMuted),
                onPressed: () => onChanged(null),
              ),
          ],
        ),
      ],
    );
  }
}

class _RelatedPetsSelector extends ConsumerWidget {
  const _RelatedPetsSelector(
      {required this.selected, required this.onChanged});

  final Set<int> selected;
  final ValueChanged<Set<int>> onChanged;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final AsyncValue<List<PetEntity>> petsAsync =
        ref.watch(currentGroupPetsProvider);
    final List<PetEntity> pets = petsAsync.maybeWhen(
      data: (List<PetEntity> l) => l,
      orElse: () => <PetEntity>[],
    );
    if (pets.isEmpty) return const SizedBox.shrink();
    return Wrap(
      spacing: 6,
      runSpacing: 6,
      children: <Widget>[
        for (final PetEntity p in pets)
          _Chip(
            label: p.name,
            selected: selected.contains(p.id),
            onTap: () {
              final Set<int> next = <int>{...selected};
              if (next.contains(p.id)) {
                next.remove(p.id);
              } else {
                next.add(p.id);
              }
              onChanged(next);
            },
          ),
      ],
    );
  }
}

